const EXPECTED = { 'Солнце': 48, 'Луна': 49, 'Марс': 39, 'Меркурий': 54, 'Юпитер': 56, 'Венера': 52, 'Сатурн': 39 };
const PLANETS = Object.keys(TABLES);

// Самопроверка таблиц при загрузке: если опечатка — сервер не стартует с неверными числами
(function selfCheck() {
  let total = 0;
  for (const p of PLANETS) {
    if (TABLES[p].length !== 8) throw new Error('Аштакаварга: ' + p + ' — не 8 источников');
    const n = TABLES[p].reduce((s, a) => s + a.length, 0);
    if (n !== EXPECTED[p]) throw new Error('Аштакаварга: сумма ' + p + ' = ' + n + ', ожидалось ' + EXPECTED[p]);
    total += n;
  }
  if (total !== 337) throw new Error('Аштакаварга: общая сумма ' + total);
})();

/**
 * @param chart — натальная карта (planets[...].sign.index, ascendant.sign.index)
 * @returns { bhinna: {планета: [12 чисел по знакам Овен..Рыбы]}, sarva: [12], lagnaIndex, houses: {bhinna, sarva по домам от лагны} }
 */
function computeAshtakavarga(chart) {
  const pos = {};
  for (const s of SRC) pos[s] = s === 'Лагна' ? chart.ascendant.sign.index : chart.planets[s].sign.index;
  const bhinna = {};
  const sarva = new Array(12).fill(0);
  for (const p of PLANETS) {
    const row = new Array(12).fill(0);
    SRC.forEach((s, i) => {
      for (const h of TABLES[p][i]) row[(pos[s] + h - 1) % 12]++;
    });
    bhinna[p] = row;
    row.forEach((v, k) => { sarva[k] += v; });
  }
  const lag = chart.ascendant.sign.index;
  const byHouse = (arr) => arr.map((_, h) => arr[(lag + h) % 12]);
  const hb = {};
  for (const p of PLANETS) hb[p] = byHouse(bhinna[p]);
  return { bhinna, sarva, lagnaIndex: lag, houses: { bhinna: hb, sarva: byHouse(sarva) }, planetSign: Object.fromEntries(PLANETS.map((p) => [p, pos[p]])) };
}

module.exports = { computeAshtakavarga, TABLES };
