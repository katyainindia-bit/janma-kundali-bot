// ============================================================
// Арудха-пады (Парашара / Джайминини), знаки целиком.
// Правило: считаем от дома h до его управителя, откладываем столько же от управителя.
// Исключения (классика): если арудха выпала в сам дом h (1-й от него) или в 7-й от него,
// берётся 10-й дом от h. Режим 'none' — без исключений.
// Управители: Скорпион — Марс, Водолей — Сатурн (без соуправителей Кету/Раху).
// ============================================================
const SIGN_LORD_NAME = ['Марс', 'Венера', 'Меркурий', 'Луна', 'Солнце', 'Меркурий', 'Венера', 'Марс', 'Юпитер', 'Сатурн', 'Сатурн', 'Юпитер'];
const NAMES = ['AL', 'A2', 'A3', 'A4', 'A5', 'A6', 'A7', 'A8', 'A9', 'A10', 'A11', 'UL'];
const TITLES = [
  'Ара-лагна (Пада-лагна): образ, как вас видят',
  'Дхана-пада: образ богатства и ресурсов',
  'Викрама-пада: образ смелости и усилий',
  'Матри-пада: образ дома и матери',
  'Мантра-пада: образ знаний и детей',
  'Шатру-пада: образ врагов и болезней',
  'Дара-пада: образ партнёров',
  'Мритью-пада: образ кризисов и перемен',
  'Бхагья-пада: образ удачи и отца',
  'Раджья-пада: образ карьеры и статуса',
  'Лабха-пада: образ доходов и желаний',
  'Упапада (УЛ): образ брака и супруга',
];

function computeArudhas(chart, mode) {
  const lag = chart.ascendant.sign.index;
  const out = [];
  for (let h = 1; h <= 12; h++) {
    const signIdx = (lag + h - 1) % 12;
    const lord = SIGN_LORD_NAME[signIdx];
    const lordSign = chart.planets[lord].sign.index;
    const p = ((lordSign - lag + 12) % 12) + 1; // дом, где стоит управитель
    let ar = (((p - 1) + (p - h)) % 12 + 12) % 12 + 1;
    let exception = false;
    if (mode !== 'none') {
      const dist = ((ar - h) % 12 + 12) % 12; // 0 — тот же дом, 6 — седьмой
      if (dist === 0 || dist === 6) { ar = ((h - 1 + 9) % 12) + 1; exception = true; }
    }
    out.push({ key: NAMES[h - 1], title: TITLES[h - 1], fromHouse: h, lord, house: ar, signIndex: (lag + ar - 1) % 12, exception });
  }
  return out;
}
module.exports = { computeArudhas };
