// --- События, выводимые из номера титхи (1-30) ---
function tithiEvents(tithiNumber, year, month, day) {
  const events = [];
  const jd = (year != null) ? jdFromDate(year, month, day, 12, 0, 0, 0) : null;
  if (tithiNumber === 15) {
    const desc = jd != null ? purnimaText(moonSignIdxAt(jd)) : null;
    events.push({ type: EVENT_TYPES.PURNIMA, label: 'Пурнима', description: desc });
  }
  if (tithiNumber === 30) {
    const desc = jd != null ? amavasyaText(moonSignIdxAt(jd)) : null;
    events.push({ type: EVENT_TYPES.AMAVASYA, label: 'Амавасья', description: desc });
  }
  if (tithiNumber === 11 || tithiNumber === 26) {
    let label = 'Экадаши', desc = null;
    if (year != null) {
      label = namedEkadashi(year, month, day, tithiNumber);
      const baseName = label.replace(' Экадаши', '');
      desc = EKADASHI_THEMES[baseName] || null;
    }
    events.push({ type: EVENT_TYPES.EKADASHI, label, description: desc });
  }
  return events;
}

// --- Санкранти: сидерический знак Солнца сегодня отличается от вчерашнего ---
const SIGN_NAMES = ['Овен','Телец','Близнецы','Рак','Лев','Дева','Весы','Скорпион','Стрелец','Козерог','Водолей','Рыбы'];

function sunSiderealSignIdx(year, month, day) {
  const jd = jdFromDate(year, month, day, 12, 0, 0, 0);
  const sidLon = pmod(sunLongitude(jd) - lahiriAyanamsha(jd), 360);
  return Math.floor(sidLon / 30);
}

function sankrantiEvent(year, month, day) {
  const todayIdx = sunSiderealSignIdx(year, month, day);
  const y = new Date(Date.UTC(year, month - 1, day) - 86400000);
  const yestIdx = sunSiderealSignIdx(y.getUTCFullYear(), y.getUTCMonth() + 1, y.getUTCDate());
  if (todayIdx !== yestIdx) {
    return { type: EVENT_TYPES.SANKRANTI, label: `Санкранти — Солнце входит в ${SIGN_NAMES[todayIdx]}` };
  }
  return null;
}

// --- Луна месяца (маса) — по накшатре Луны в БЛИЖАЙШЕЕ полнолуние вперёд ---
// Классическое правило (стих Амаракоши): "Пушья + полнолуние = Пауша маса" —
// то есть месяц называется по накшатре, в которой Луна находится ровно в
// момент полнолуния, которым этот месяц заканчивается (Пурнимmanta-счёт).
// Раньше здесь было приближение "по знаку Солнца" — но проверка на реальных
// датах (Дивали, Холи, Джанмаштами) показала систематическую ошибку на один
// месяц у этого приближения, потому что лунный и солнечный циклы расходятся
// в течение года. Поэтому считаем по-настоящему: ищем ближайшее вперёд
// полнолуние, берём накшатру Луны там, и относим её к ближайшей из 12
// классических опорных накшатр (Читра, Вишакха и т.д.) — по кольцевому
// расстоянию, а не по произвольно расставленным границам.
function tithiNumberAt(jd) {
  const diff = pmod(moonLongitude(jd) - sunLongitude(jd), 360);
  return Math.floor(diff / 12) + 1;
}
function findNextPurnimaJd(jd) {
  for (let d = 0; d <= 35; d++) {
    if (tithiNumberAt(jd + d) === 15) return jd + d;
  }
  return jd; // не должно происходить — подстраховка
}
function moonNakshatraIdxAt(jd) {
  const sidLon = pmod(moonLongitude(jd) - lahiriAyanamsha(jd), 360);
  return Math.floor(sidLon / (360 / 27));
}
const MASA_REFERENCE_NAKSHATRA = {
  'Чайтра': 13, 'Вайшакха': 15, 'Джьештха': 17, 'Ашадха': 19, 'Шравана': 21,
  'Бхадрапада': 24.5, 'Ашвина': 0, 'Картика': 2, 'Маргаширша': 4,
  'Пауша': 7, 'Магха': 9, 'Пхалгуна': 10.5,
};
function nakshatraIdxToMasa(nakIdx) {
  let best = null, bestDist = Infinity;
  for (const [masa, refIdx] of Object.entries(MASA_REFERENCE_NAKSHATRA)) {
    let dist = Math.abs(nakIdx - refIdx);
    dist = Math.min(dist, 27 - dist);
    if (dist < bestDist) { bestDist = dist; best = masa; }
  }
  return best;
}
function currentMasa(year, month, day) {
  const jd = jdFromDate(year, month, day, 12, 0, 0, 0);
  const purnimaJd = findNextPurnimaJd(jd);
  return nakshatraIdxToMasa(moonNakshatraIdxAt(purnimaJd));
}

