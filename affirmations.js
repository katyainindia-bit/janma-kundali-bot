function pickAffirmation(house, tone, dayNumber) {
  const byHouse = AFFIRMATIONS[house];
  if (!byHouse) return null;
  const list = byHouse[tone] || byHouse.moderate;
  if (!list || !list.length) return null;
  const n = Number.isFinite(dayNumber) ? dayNumber : 0;
  return list[((n % list.length) + list.length) % list.length];
}

